const validCoverId = value => typeof value === 'string' && value.length <= 100 &&
  value === value.normalize('NFC') && /^[\p{L}\p{Nd}_-]+$/u.test(value);
const validCoverTitle = value => typeof value === 'string' && value.length <= 200 && value.trim().length > 0;
const validCoverPath = value => typeof value === 'string' && value.length > 0 && value.length <= 300 &&
  !value.startsWith('/') && !value.includes('..') && !value.includes('//') &&
  !/^[a-z][a-z\d+.-]*:/i.test(value) && !/[\\\x00-\x20\x7f?#%\uD800-\uDFFF]/u.test(value);

function selectHomepageCovers(catalog) {
  if (!Array.isArray(catalog?.categories)) return [];

  const categories = new Set();
  const courseIds = new Set();
  const groups = [];
  for (const category of catalog.categories) {
    if (!validCoverId(category?.id) || !validCoverTitle(category.name) || categories.has(category.id)) continue;
    categories.add(category.id);
    if (!Array.isArray(category.series)) continue;

    const courses = [];
    for (const course of category.series) {
      if (!validCoverId(course?.id) || courseIds.has(course.id) || !validCoverTitle(course.title) ||
          !validCoverPath(course.coverPath) || !['ongoing', 'completed'].includes(course.status)) continue;
      courseIds.add(course.id);
      const { id, title, coverPath, status, updatedAt } = course;
      const timestamp = Number.isInteger(updatedAt) && updatedAt > 0 && updatedAt < 1e11 ? updatedAt : 0;
      courses.push({ id, title, coverPath, status, timestamp });
    }
    groups.push(courses);
  }

  const latestFirst = (a, b) => b.timestamp - a.timestamp;
  const chosen = groups.flat().filter(course => course.status === 'ongoing').sort(latestFirst).slice(0, 10);
  const latestIds = new Set(chosen.map(course => course.id));
  const remainingGroups = groups.map(group => group.filter(course => !latestIds.has(course.id)).sort(latestFirst));

  for (let index = 0; chosen.length < homepageCovers.length; index++) {
    const round = remainingGroups.map(group => group[index]).filter(Boolean);
    if (!round.length) break;
    chosen.push(...round.slice(0, homepageCovers.length - chosen.length));
  }

  return chosen.map(({ title, coverPath, id }) => [title, coverPath, id]);
}

async function loadHomepageCovers(origin) {
  const limit = 10 * 1024 * 1024;
  const response = await fetch(origin + '/index.json', { cache: 'no-cache' });
  if (!response.ok || !response.body || Number(response.headers.get('Content-Length')) > limit) return [];

  let size = 0;
  const body = response.body.pipeThrough(new TransformStream({
    transform(chunk, controller) {
      size += chunk.byteLength;
      if (size > limit) throw new RangeError('课程目录过大');
      controller.enqueue(chunk);
    },
  }));
  return selectHomepageCovers(await new Response(body).json());
}
